public class Kilo
{
    public static void main(String[] args)
    {
        int i;
        int count = 0;
        for (i = 1; i <= 5; i++)
        {
            count++;
            System.out.println("Number " + i);
        }
        System.out.println("Count = " + count);
    }
}
